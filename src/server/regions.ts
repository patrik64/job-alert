// whole words: no ascii letter or digit on either side, so separators,
// hyphens and accented letters all count as breaks
const wordsSource = (words: string[]) =>
	`(?<![a-z0-9])(?:${words.map((w) => w.replaceAll(' ', '[\\s-]+')).join('|')})(?![a-z0-9])`;

// a code closing a place: after a comma, maybe with a zip code, and then
// the end of the line or of one of its places
const codesSource = (codes: string[]) =>
	`,\\s*(?:${codes.join('|')})(?:\\s+\\d{5}(?:-\\d{4})?)?(?=\\s*(?:$|[;·•|/()\\[\\]]|[-–—]\\s))`;

const AREAS = Object.keys(PLACES) as Area[];

// each area as its two patterns
const MATCHERS = AREAS.map((area) => {
	const { words, codes } = PLACES[area];
	return {
		area,
		words: new RegExp(wordsSource(words), 'i'),
		codes: codes ? new RegExp(codesSource(codes)) : null
	};
});

// the regions a location puts a job within reach of; none when it names no
// place at all ("Remote", "Hybrid", an office's name)
export function regionsOf(location: string): Region[] {
	const areas = new Set(
		MATCHERS.filter((m) => m.words.test(location) || m.codes?.test(location)).map((m) => m.area)
	);
	return REGIONS.filter((r) => COVERS[r].some((a) => areas.has(a)));
}

// whether a location's regions (from regionsOf) meet any of the wanted
// ones — 'unknown' standing for the lines that name no place
export const inRegions = (regions: Region[], wanted: readonly (Region | 'unknown')[]) =>
	regions.length === 0 ? wanted.includes('unknown') : regions.some((r) => wanted.includes(r));

