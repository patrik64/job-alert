// Where a job can be done from, as far as the location line its board
// publishes says: "San Francisco, CA, USA", "Berlin, BE, DE", "Remote;
// Europe", "EMEA · remote", "London". The lines follow no one format, so
// they are read for the places they name — countries, their regions and
// cities, the codes some boards abbreviate them to, and stretches of the
// world like EMEA — and a job is placed wherever its line points. This runs
// here rather than in the database: postgres needs seconds for what takes
// milliseconds here, so the api reads just the distinct lines off it.

// the regions a caller can ask for
export const REGIONS = [
	'eu',
	'uk',
	'europe',
	'us',
	'canada',
	'latam',
	'apac',
	'mena',
	'africa'
] as const;
export type Region = (typeof REGIONS)[number];

// what a location line can name: a place in one of the regions — Europe
// split three ways, since the eu (with the countries sharing its free
// movement) and the uk hire differently — or a stretch of the world as a
// whole
